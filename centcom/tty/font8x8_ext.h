#pragma once
#include <stdint.h>

/* Расширенные глифы для ANSI Shadow арта.
   Используются через байты 0x01-0x07 в строковых литералах:
     0x01 = █ (сплошной блок)
     0x02 = ╗ (верхний правый угол)
     0x03 = ╔ (верхний левый угол)
     0x04 = ╚ (нижний левый угол)
     0x05 = ╝ (нижний правый угол)
     0x06 = ═ (двойная горизонталь)
     0x07 = ║ (двойная вертикаль)
*/
static const uint8_t font8x8_ext[8][8] = {
    {0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00}, /* 0: пусто */
    {0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF,0xFF}, /* 1: █ */
    {0xFF,0xFF,0x03,0x03,0x03,0x03,0x03,0x03}, /* 2: ╗ */
    {0xFF,0xFF,0xC0,0xC0,0xC0,0xC0,0xC0,0xC0}, /* 3: ╔ */
    {0xC0,0xC0,0xC0,0xC0,0xC0,0xC0,0xFF,0xFF}, /* 4: ╚ */
    {0x03,0x03,0x03,0x03,0x03,0x03,0xFF,0xFF}, /* 5: ╝ */
    {0x00,0x00,0x00,0xFF,0xFF,0x00,0x00,0x00}, /* 6: ═ */
    {0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x18}, /* 7: ║ */
};